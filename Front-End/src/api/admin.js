import { api, fetchAll, download } from "./client";
import { splitName, toFavoriteProduct, toOrder, toUser } from "./mappers";

// The admin form uses one "full name" field; the API stores first/last names.
// An empty password on edit keeps the current one.
const fromUserForm = (form) => ({
  ...splitName(form.userFullName),
  email: form.userEmail,
  phone: form.phone ?? "",
  password: form.userPassword ?? "",
  role: form.role,
  is_active: form.status !== "inactive",
});

export const fetchUsers = async () =>
  (await fetchAll("/api/admin/users")).map(toUser);
export const fetchUserDetails = async (id) => {
  const data = await api(`/api/admin/users/${id}`);
  return {
    user: toUser(data.user),
    orders: (data.orders ?? []).map(toOrder),
    favorites: (data.favorites ?? []).map(toFavoriteProduct),
  };
};
export const createUser = async (form) =>
  toUser(
    await api("/api/admin/users", { method: "POST", body: fromUserForm(form) }),
  );
export const updateUser = async (id, form) =>
  toUser(
    await api(`/api/admin/users/${id}`, {
      method: "PUT",
      body: fromUserForm(form),
    }),
  );
// Users with orders are deactivated instead of deleted; the reply says which.
export const deleteUser = (id) =>
  api(`/api/admin/users/${id}`, { method: "DELETE" });

export const fetchAllOrders = async () =>
  (await fetchAll("/api/admin/orders")).map(toOrder);
export const updateOrderStatus = (id, status) =>
  api(`/api/admin/orders/${id}/status`, { method: "PUT", body: { status } });
// The order's private admin note ("" clears it). Returns the updated order.
export const saveOrderNote = async (id, note) =>
  toOrder(
    await api(`/api/admin/orders/${id}/note`, {
      method: "PUT",
      body: { note },
    }),
  );
export const fetchAdminOrder = async (id) =>
  toOrder(await api(`/api/admin/orders/${id}`));

// CSV downloads, generated by the backend: every matching row, Excel-ready.
// filters: { from, to (YYYY-MM-DD), status, paymentMethod }
export const downloadOrdersCsv = (filters = {}) => {
  const q = new URLSearchParams();
  if (filters.from) q.set("from", filters.from);
  if (filters.to) q.set("to", filters.to);
  if (filters.status) q.set("status", filters.status);
  if (filters.paymentMethod) q.set("payment_method", filters.paymentMethod);
  const qs = q.toString();
  return download(
    `/api/admin/exports/orders.csv${qs ? `?${qs}` : ""}`,
    "orders.csv",
  );
};
export const downloadCustomersCsv = () =>
  download("/api/admin/exports/customers.csv", "customers.csv");
